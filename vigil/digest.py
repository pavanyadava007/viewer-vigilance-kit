"""Weekly digest writer: Markdown + CSV with counts per source and category."""

from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path

from .schema import Incident

SOURCES = ["FDA_MAUDE", "FDA_RECALL", "BFARM_FSN"]


def counts(items: list[Incident]) -> dict:
    by_source = Counter(it.source for it in items)
    rel = Counter(it.source for it in items if it.relevant)
    cats: Counter = Counter()
    for it in items:
        if it.relevant:
            for t in it.tags or ["untagged"]:
                cats[(it.source, t)] += 1
    return {"by_source": by_source, "relevant": rel, "by_category": cats}


def _md_escape(s: str) -> str:
    return s.replace("|", "/").replace("\n", " ").strip()


def write_csv(items: list[Incident], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    cols = ["source", "id", "date", "manufacturer", "product", "product_code", "event_type"]
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow([*cols, "relevant", "tags", "url"])
        for it in items:
            row = [getattr(it, c) for c in cols]
            w.writerow([*row, int(it.relevant), ";".join(it.tags), it.url])


def render_markdown(
    items: list[Incident], title: str, period: str, max_rows: int = 40, note: str = ""
) -> str:
    c = counts(items)
    cats = sorted({t for (_, t) in c["by_category"]})
    lines = [f"# {title}", "", f"Period: {period}", ""]
    if note:
        lines += [note, ""]
    lines += ["## Counts per source", "", "| Source | New items | Viewer/imaging relevant |"]
    lines += ["|---|---:|---:|"]
    for s in SOURCES:
        lines.append(f"| {s} | {c['by_source'].get(s, 0)} | {c['relevant'].get(s, 0)} |")
    lines += ["", "## Relevant items per category", ""]
    if cats:
        lines.append("| Category | " + " | ".join(SOURCES) + " |")
        lines.append("|---|" + "---:|" * len(SOURCES))
        for t in cats:
            vals = " | ".join(str(c["by_category"].get((s, t), 0)) for s in SOURCES)
            lines.append(f"| {t} | {vals} |")
    else:
        lines.append("No relevant items.")
    prio = {"FDA_RECALL": 0, "BFARM_FSN": 1, "FDA_MAUDE": 2}
    rel = sorted((it for it in items if it.relevant), key=lambda i: i.date, reverse=True)
    rel.sort(key=lambda i: (prio.get(i.source, 9), not i.tags))  # stable: keeps date order
    lines += ["", f"## Relevant items (recalls, then FSNs, then MAUDE; max {max_rows})", ""]
    if rel:
        lines.append("| Date | Source | Manufacturer | Product | Code / group | Tags | Link |")
        lines.append("|---|---|---|---|---|---|---|")
        for it in rel[:max_rows]:
            lines.append(
                f"| {it.date} | {it.source} | {_md_escape(it.manufacturer)[:40]} | "
                f"{_md_escape(it.product)[:60]} | {_md_escape(it.product_code)[:45]} | "
                f"{', '.join(it.tags) or '-'} | [open]({it.url}) |"
            )
    else:
        lines.append("None.")
    lines += [
        "",
        "Generated by viewer-vigilance-kit. Rule-based triage aid only; every item needs "
        "manual review against the source record.",
        "",
    ]
    return "\n".join(lines)
